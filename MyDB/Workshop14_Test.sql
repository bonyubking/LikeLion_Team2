DROP TABLE DISCARDED_PRODUCT;

CREATE TABLE DISCARDED_PRODUCT
(PDNO INT PRIMARY KEY,
	PDNAME VARCHAR(10),
    PDSUBNAME VARCHAR(10),
    FACTNO VARCHAR(5) REFERENCES FACTORY(FACTNO),
    PDDATE DATE,
    PDCOST INT,
    PDPRICE INT,
    PDAMOUNT INT,
    DISCARDED_DATE DATE);
    
