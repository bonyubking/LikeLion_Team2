-- 1. ECOMMERCE 스키마를 생성하시오. 
USE ECOMMERCE;
CREATE SCHEMA ECOMMERCE;

-- 2. 비밀번호가 123QWE!@#인 SHOP_WEB 사용자를 생성하시오
CREATE USER 'SHOP_WEB'@'localhost' IDENTIFIED BY '123QWE!@#';  

-- 3. 비밀번호가 123QWE!@#인 SHOP_ADMIN 사용자를 생성하시오 
CREATE USER 'SHOP_ADMIN'@'localhost' IDENTIFIED BY '123QWE!@#';

 -- 4. SHOP_WEB 사용자에게 ECOMMERCE 스키마에 존재하는 모든 테이블에 대한 SELECT, 
-- INSERT, UPDATE, DELTE 권한을 부여하고 SHOW GRANTS 명령어를 사용해 확인 하시오 
GRANT SELECT, INSERT, UPDATE, DELETE 
ON ECOMMERCE.* TO 'SHOP_WEB'@'localhost';
FLUSH PRIVILEGES;  
SHOW GRANTS FOR 'SHOP_WEB'@'localhost';

-- 5. SHOP_ADMIN 사용자에게 ECOMMERCE 스키마에 대한 모든 권한과, 해당 권한을 다른 
-- 사용자에게 부여할 수 있는 권한을 부여하시오. 이후 SHOW GRANTS 명령어를 사용해 
-- 확인 하시오 

GRANT ALL PRIVILEGES ON ECOMMERCE.* TO 'SHOP_ADMIN'@'localhost' 
WITH GRANT OPTION;
FLUSH PRIVILEGES;
SHOW GRANTS FOR 'SHOP_ADMIN'@'localhost';  

-- 6. SHOP_WEB 의 INSERT 권한을 회수하고 SHOW GRANTS 명령어로 확인 하시오
REVOKE INSERT ON ECOMMERCE.* FROM 'SHOP_WEB'@'localhost';
FLUSH PRIVILEGES;  
SHOW GRANTS FOR 'SHOP_WEB'@'localhost';

-- 7. 'ROLE_WEB' 이란 이름을 가지는 ROLE 을 생성 하시오 
CREATE ROLE ROLE_WEB;

-- 8. 'ROLE_WEB' 에 ECOMMERCE 스키마에 대한 SELECT, INSERT, UPDATE, DELETE, 
-- CREATE 권한을 부여하고 SHOW GRANTS 명령어를 사용해 확인 하시오.
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE ON ECOMMERCE.* TO ROLE_WEB;
SHOW GRANTS FOR ROLE_WEB; 

-- 9. 'ROLE_WEB' ROLE 을 SHOP_WEB 사용자에게 부여 하시오. 
GRANT 'ROLE_WEB' TO 'SHOP_WEB'@'localhost';

-- 10. 'ROLE_WEB'을 SHOP_WEB 사용자로부터 회수 하시오. 
REVOKE 'ROLE_WEB' FROM 'SHOP_WEB'@'localhost';

-- 11.  주어진 ERD 내용대로 USER, ORDER, CATEGORY 테이블을 생성 하시오. 
-- ORDER 와 CATEGORY 테이블의 기본키는 1부터 시작하며 자동으로 1씩 증가하도록 

CREATE TABLE USER(
	Userid VARCHAR(255) PRIMARY KEY,
	Username VARCHAR(255) NOT NULL,
	Email VARCHAR(255) NOT NULL,
	Address TEXT,   
	PhoneNumber VARCHAR(20),   
	regDate TIMESTAMP
);

CREATE TABLE ORDERS(
	OrderID INT PRIMARY KEY AUTO_INCREMENT,
	UserID INT,  
	OrderDate TIMESTAMP NOT NULL,
	TotalAmount DECIMAL(10,2) NOT NULL, 
	ShippingAddress TEXT,  
	IsShipped BOOLEAN
);

CREATE TABLE CATEGORY(
	CategoryID INT PRIMARY KEY AUTO_INCREMENT,
	UpperCategory TEXT,
	CategoryName VARCHAR(255) NOT NULL,
	Description TEXT);
    
-- 12. 주어진 ERD 내용대로 USERFAVORITE 테이블을 생성 하시오. 이때 USERID컬럼이 
-- USER 테이블의 USERID 컬럼을 외래키로 참조하도록 하시오. 기본키는 1부터 시작하며 
-- 자동으로 1씩 증가하도록 지정 하시오. 

CREATE TABLE USERFAVORITE(
	FavoriteID INT PRIMARY KEY AUTO_INCREMENT,
    UserID VARCHAR(255), 
	FOREIGN KEY(UserID) REFERENCES USER(Userid),
	ProductID INT, 
	regDate TIMESTAMP 
