-- 13. 주어진 ERD 내용대로 ORDERDETAIL 테이블을 생성 하시오. 이때 ORDERID컬럼이 
-- ORDER 테이블의 ORDERID 컬럼을 외래키로 참조하도록 하시오. 기본키는 1부터 
-- 시작하며 자동으로 1씩 증가하도록 지정 하시오.

CREATE TABLE ORDERDETAIL(
	OrderDetailID INT PRIMARY KEY AUTO_INCREMENT, 
	OrderID INT,   
	ProductID INT, 
	Quantity INT NOT NULL,
    FOREIGN KEY(OrderID) REFERENCES ORDERS(OrderId)
);

-- 14. 주어진 ERD 내용대로 PAYMENT 테이블을 생성 하시오. 이때 ORDERID컬럼이 
-- ORDER 테이블의 ORDERID 컬럼을 외래키로 참조하도록 하시오. 기본키는 1부터 
-- 시작하며 자동으로 1씩 증가하도록 지정 하시오.

CREATE TABLE PAYMENT(
	PaymentID INT PRIMARY KEY AUTO_INCREMENT,
	OrderID INT,
	PaymentMethod VARCHAR(50) NOT NULL,
	TransactionDate DATE NOT NULL,
	PayAmount DECIMAL(10,2) NOT NULL, 
	IsSuccessful BOOLEAN,
    FOREIGN KEY(OrderID) REFERENCES ORDERS(OrderId)
);

-- 15. 주어진 ERD 내용대로 PRODUCT 테이블을 생성 하시오. 이때 CATEGORYID컬럼이 
-- CATEGORY 테이블의 CATEGORYID 컬럼을 외래키로 참조하도록 하시오.

CREATE TABLE PRODUCT(
	ProductID INT PRIMARY KEY,
	CategoryID INT NOT NULL,
	ProductName VARCHAR(255) NOT NULL, 
	Price DECIMAL(10,2) NOT NULL,
	StockQuantity INT NOT NULL,
	Description TEXT, 
	Manufacturer VARCHAR(100),
	regDate TIMESTAMP,
    FOREIGN KEY(CategoryID) REFERENCES CATEGORY(CategoryID)
);


